#!/usr/bin/env python3
"""
usage 1: hex2mem.py image.hex out_prefix
usage 2: hex2mem.py --bootrom bootloader.hex out.mem   (2048 words from 0xF000)
usage 3: hex2mem.py --gowin-init bootloader.hex out.vh
         Verilog defines with INIT_RAM values for the flash blocks that hold
         the boot section (word 0x7800-0x7FFF = block 15 of each bank).

Split an AVR flash image (Intel HEX, e.g. the Uzebox bootloader) into the
two $readmemh files used to initialise UzeTang's banked flash:
  <prefix>_e.mem  even words (16K x 16 bit)
  <prefix>_o.mem  odd words  (16K x 16 bit)
Unused flash is 0xFFFF (erased).

usage: hex2mem.py image.hex out_prefix
"""
import sys

def read_hex(fn):
    mem = bytearray(b"\xff" * 65536)
    base = 0
    for line in open(fn):
        line = line.strip()
        if not line.startswith(":"):
            continue
        n = int(line[1:3], 16); a = int(line[3:7], 16); t = int(line[7:9], 16)
        d = bytes.fromhex(line[9:9 + 2 * n])
        if t == 0:
            for i, b in enumerate(d):
                if base + a + i < 65536:
                    mem[base + a + i] = b
        elif t == 2:
            base = int.from_bytes(d, "big") << 4
        elif t == 4:
            base = int.from_bytes(d, "big") << 16
        elif t == 1:
            break
    return mem

def main():
    if sys.argv[1] == "--gowin-init":
        mem = read_hex(sys.argv[2])
        words = [mem[2 * i] | (mem[2 * i + 1] << 8) for i in range(32768)]
        with open(sys.argv[3], "w") as f:
            f.write("// Generated by tools/hex2mem.py from %s - do not edit\n" % sys.argv[2].split("/")[-1])
            f.write("// INIT_RAM values for flash block 15 (boot section) of each bank\n")
            for bank, name in ((0, "E"), (1, "O")):
                bw = words[bank::2][15 * 1024:16 * 1024]      # bank word 0x3C00..0x3FFF
                for r in range(64):
                    v = 0
                    for k in range(16):
                        v |= bw[r * 16 + k] << (16 * k)
                    f.write("`define BOOTINIT_%s_%02X 256'h%064X\n" % (name, r, v))
        print("%s -> %s" % (sys.argv[2], sys.argv[3]))
        return
    if sys.argv[1] == "--bootrom":
        mem = read_hex(sys.argv[2])
        with open(sys.argv[3], "w") as f:
            for i in range(2048):
                a = 0xF000 + 2 * i
                f.write("%04X\n" % (mem[a] | (mem[a + 1] << 8)))
        print("%s -> %s (boot ROM, 4 KB at 0xF000)" % (sys.argv[2], sys.argv[3]))
        return
    mem = read_hex(sys.argv[1])
    words = [mem[2 * i] | (mem[2 * i + 1] << 8) for i in range(32768)]
    for suffix, sel in (("_e", 0), ("_o", 1)):
        with open(sys.argv[2] + suffix + ".mem", "w") as f:
            for i in range(sel, 32768, 2):
                f.write("%04X\n" % words[i])
    used = sum(1 for w in words if w != 0xFFFF)
    print("%s -> %s_e.mem / %s_o.mem (%d words used)" % (sys.argv[1], sys.argv[2], sys.argv[2], used))

if __name__ == "__main__":
    main()
